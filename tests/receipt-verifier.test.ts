describe("Cryptographic Receipt Verifier & Tamper Detection", () => {
	it("verifies an authentic multi-task receipt generated by MeshOrchestrator", async () => {
		const pc = new PermissionController();
		pc.setPromptCallback(async () => "grant_session");

		const plan = MeshOrchestrator.plan(
			"Audit https://mozilla.org for carbon emissions, privacy trackers, and verify claims",
		);
		const { receipt } = await MeshOrchestrator.execute(plan, pc);

		const sdkCheck = await AgentCrypto.verifyReceipt(receipt);
		expect(sdkCheck.valid).toBe(true);

		const result = await verifyExecutionReceipt(JSON.stringify(receipt));
		expect(result.valid).toBe(true);
		expect(result.tampered).toBe(false);
		expect(result.checks.length).toBe(6);
		expect(result.checks.every((c) => c.passed)).toBe(true);
		expect(result.recomputedMerkleRoot).toBe(
			receipt.cryptographicProof.merkleRoot,
		);
		expect(result.recomputedSignature).toBe(
			receipt.cryptographicProof.signature,
		);
	});

	it("generates a valid signed sample receipt and immediately catches 1-char Simulate Tamper", async () => {
		const sample = await generateSampleSignedReceipt();
		const sampleJson = JSON.stringify(sample, null, 2);

		const validResult = await verifyExecutionReceipt(sampleJson);
		expect(validResult.valid).toBe(true);
		expect(validResult.tampered).toBe(false);

		const tampered = simulateReceiptTamper(sampleJson);
		expect(tampered.fieldChanged).toBe("taskReceipts[0].outputHash");
		expect(tampered.originalChar).not.toBe(tampered.tamperedChar);

		const tamperedResult = await verifyExecutionReceipt(tampered.tamperedJson);
		expect(tamperedResult.valid).toBe(false);
		expect(tamperedResult.tampered).toBe(true);

		const merkleCheck = tamperedResult.checks.find(
			(c) => c.id === "merkle_root",
		);
		const sigCheck = tamperedResult.checks.find((c) => c.id === "signature");
		const receiptIdCheck = tamperedResult.checks.find(
			(c) => c.id === "receipt_id",
		);
		expect(merkleCheck?.passed).toBe(false);
		expect(sigCheck?.passed).toBe(false);
		expect(receiptIdCheck?.passed).toBe(false);
	});

	it("detects tampering across signature, merkleRoot, clientDid, receiptId, inputHash, and task count", async () => {
		const base = await generateSampleSignedReceipt();

		// 1. Tamper signature (1 char)
		const badSig = structuredClone(base);
		badSig.cryptographicProof.signature = `${badSig.cryptographicProof.signature.slice(0, -1)}${badSig.cryptographicProof.signature.endsWith("0") ? "1" : "0"}`;
		expect((await verifyExecutionReceipt(badSig)).valid).toBe(false);
		expect((await AgentCrypto.verifyReceipt(badSig)).valid).toBe(false);

		// 2. Tamper merkleRoot (1 char)
		const badMerkle = structuredClone(base);
		badMerkle.cryptographicProof.merkleRoot = `${badMerkle.cryptographicProof.merkleRoot.slice(0, -1)}${badMerkle.cryptographicProof.merkleRoot.endsWith("a") ? "b" : "a"}`;
		expect((await verifyExecutionReceipt(badMerkle)).valid).toBe(false);
		expect((await AgentCrypto.verifyReceipt(badMerkle)).valid).toBe(false);

		// 3. Tamper task inputHash (1 char)
		const badInput = structuredClone(base);
		const origIn = badInput.taskReceipts[0].inputHash;
		badInput.taskReceipts[0].inputHash = `${origIn.slice(0, -1)}${origIn.endsWith("f") ? "0" : "f"}`;
		expect((await verifyExecutionReceipt(badInput)).valid).toBe(false);

		// 4. Tamper clientDid
		const badDid = structuredClone(base);
		badDid.clientDid = `${badDid.clientDid.slice(0, -1)}x`;
		expect((await verifyExecutionReceipt(badDid)).valid).toBe(false);

		// 5. Tamper receiptId
		const badId = structuredClone(base);
		badId.receiptId = `${badId.receiptId.slice(0, -1)}9`;
		expect((await verifyExecutionReceipt(badId)).valid).toBe(false);

		// 6. Tamper executedTasksCount
		const badCount = structuredClone(base);
		badCount.executedTasksCount = 999;
		expect((await verifyExecutionReceipt(badCount)).valid).toBe(false);
	});

	it("returns structured parse errors for empty, malformed JSON, or wrong schema", async () => {
		const emptyRes = await verifyExecutionReceipt("   ");
		expect(emptyRes.valid).toBe(false);
		expect(emptyRes.parseError).toBeDefined();

		const syntaxRes = await verifyExecutionReceipt("{not valid json");
		expect(syntaxRes.valid).toBe(false);
		expect(syntaxRes.parseError).toContain("Invalid JSON");

		const schemaRes = await verifyExecutionReceipt(
			JSON.stringify({ hello: "world" }),
		);
		expect(schemaRes.valid).toBe(false);
		expect(schemaRes.parseError).toContain("VerifiableReceipt schema");
	});
});

describe("Optional BYOK / Local Ollama RAM-Only LLM Config", () => {
	afterEach(() => {
		clearRamLlmSecrets();
	});

	it("defaults to keyless mode and wipes RAM keys cleanly", () => {
		const initial = getRamLlmConfig();
		expect(initial.provider).toBe("none");
		expect(initial.apiKey).toBe("");
		expect(isLlmActive(initial)).toBe(false);
		expect(toSdkLlmConfig(initial).provider).toBe("in-browser-mock");

		const armed = setRamLlmConfig({
			provider: "openai",
			apiKey: "sk-ephemeral-ram-only-test",
			endpoint: "https://api.openai.com/v1/chat/completions",
			model: "gpt-4o-mini",
		});
		expect(isLlmActive(armed)).toBe(true);
		expect(toSdkLlmConfig(armed).provider).toBe("byok-openai");
		expect(toSdkLlmConfig(armed).apiKey).toBe("sk-ephemeral-ram-only-test");

		const wiped = clearRamLlmSecrets();
		expect(wiped.provider).toBe("none");
		expect(wiped.apiKey).toBe("");
		expect(getRamLlmConfig().apiKey).toBe("");
	});

	it("probes Local Ollama /api/tags and synthesizes via custom fetch cleanly", async () => {
		const ollamaCfg = setRamLlmConfig({
			provider: "ollama",
			apiKey: "",
			endpoint: "http://localhost:11434",
			model: "llama3.2:1b",
		});
		expect(isLlmActive(ollamaCfg)).toBe(true);
		expect(toSdkLlmConfig(ollamaCfg).provider).toBe("ollama");

		const mockFetch = (async (url: string | URL) => {
			const s = String(url);
			if (s.endsWith("/api/tags")) {
				return new Response(
					JSON.stringify({ models: [{ name: "llama3.2:1b" }] }),
					{ status: 200, headers: { "Content-Type": "application/json" } },
				);
			}
			return new Response(
				JSON.stringify({ response: "Local Ollama summary complete." }),
				{ status: 200, headers: { "Content-Type": "application/json" } },
			);
		}) as typeof fetch;

		const probe = await testLlmConnection(ollamaCfg, mockFetch);
		expect(probe.ok).toBe(true);
		expect(probe.availableModels).toContain("llama3.2:1b");

		const synth = await synthesizeWithOptionalLlm(
			ollamaCfg,
			"Audit site",
			[{ eco: "A+" }],
			mockFetch,
		);
		expect(synth.usedLlm).toBe(true);
		expect(synth.source).toBe("LOCAL_OLLAMA");
		expect(synth.summary).toContain("Local Ollama summary complete.");
	});
});

describe("Network Provenance Badges & Live Self-Manifest Discovery", () => {
	afterEach(() => {
		AgentRegistry.resetToBuiltins();
	});

	it("classifies LIVE NETWORK FETCH vs CORS FALLBACK accurately", () => {
		const liveTask = resolveNetworkProvenance({
			status: "completed",
			networkMode: "LIVE NETWORK FETCH",
			outputs: { targetUrl: "https://mozilla.org" },
		});
		expect(liveTask?.badgeLabel).toBe("LIVE NETWORK FETCH");
		expect(liveTask?.mode).toBe("live_network_fetch");

		const underscoreLive = resolveNetworkProvenance({
			status: "completed",
			outputs: { dataSource: "LIVE_NETWORK_FETCH" },
		});
		expect(underscoreLive?.badgeLabel).toBe("LIVE NETWORK FETCH");

		const fallbackTask = resolveNetworkProvenance({
			status: "completed",
			networkMode: "CORS FALLBACK",
			outputs: { targetUrl: "https://example.com" },
		});
		expect(fallbackTask?.badgeLabel).toBe("CORS FALLBACK");
		expect(fallbackTask?.mode).toBe("cors_fallback");
	});

	it("discovers and validates ./.well-known/agent.json as LIVE NETWORK FETCH", async () => {
		expect(normalizeManifestUrl(SELF_MANIFEST_PATH)).toBe(
			"./.well-known/agent.json",
		);
		expect(normalizeManifestUrl("example.org")).toBe(
			"https://example.org/.well-known/agent.json",
		);

		const selfManifestPath = resolve(
			process.cwd(),
			"public/.well-known/agent.json",
		);
		const selfManifestText = readFileSync(selfManifestPath, "utf8");

		const mockSelfFetch = (async () =>
			new Response(selfManifestText, {
				status: 200,
				headers: { "Content-Type": "application/json" },
			})) as typeof fetch;

		const liveRes = await discoverLiveManifest(SELF_MANIFEST_PATH, {
			allowCorsFallback: false,
			fetchImpl: mockSelfFetch,
		});
		expect(liveRes.ok).toBe(true);
		expect(liveRes.mode).toBe("LIVE NETWORK FETCH");
		expect(liveRes.card?.id).toBe(
			"did:web:nexusagent.org:agents:mesh-coordinator",
		);
		expect(
			AgentRegistry.get("did:web:nexusagent.org:agents:mesh-coordinator"),
		).toBeDefined();

		// Test CORS fallback transparency when remote origin blocks fetch
		const failingFetch = (async () => {
			throw new TypeError("Failed to fetch (CORS blocked)");
		}) as typeof fetch;

		const fallbackRes = await discoverLiveManifest("https://blocked.example", {
			allowCorsFallback: true,
			fetchImpl: failingFetch,
		});
		expect(fallbackRes.ok).toBe(true);
		expect(fallbackRes.mode).toBe("CORS FALLBACK");
		expect(fallbackRes.notice).toContain("CORS FALLBACK");
	});
});
